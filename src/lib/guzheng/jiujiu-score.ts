export type JiujiuLyricCue = {
  id: string;
  text: string;
};

export type JiujiuScorePage = {
  image: string;
  title: string;
  note: string;
  lyrics: JiujiuLyricCue[];
};

function cues(page: number, lines: string[]): JiujiuLyricCue[] {
  return lines.map((text, index) => ({ id: `p${page}-${index + 1}`, text }));
}

